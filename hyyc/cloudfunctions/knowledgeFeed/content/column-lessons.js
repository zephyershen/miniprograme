function publicLesson(value, { includeCopy = true } = {}) {
  const preview = {
    id: value.id,
    kind: value.kind,
    track: value.track,
    order: value.order,
    term: value.term,
    title: value.title
  };
  return includeCopy
    ? {
      ...preview,
      subtitle: value.subtitle,
      duration: value.duration,
      tags: Array.isArray(value.tags) ? [...value.tags] : []
    }
    : preview;
}

function findLesson(lessonId) {
  return COLUMN_LESSONS.find((item) => item.id === lessonId) || null;
}

module.exports = { COLUMN_TRACKS, COLUMN_LESSONS, publicLesson, findLesson };
